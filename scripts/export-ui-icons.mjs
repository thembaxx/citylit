import { mkdir, writeFile } from "node:fs/promises";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
// Import only the definitions we use. Offline pages never need React or a remote icon service.
import ArrowUpRight01Icon from "@hugeicons/core-free-icons/ArrowUpRight01Icon";
import ArrowLeft01Icon from "@hugeicons/core-free-icons/ArrowLeft01Icon";
import ArrowRight01Icon from "@hugeicons/core-free-icons/ArrowRight01Icon";
import RotateClockwiseIcon from "@hugeicons/core-free-icons/RotateClockwiseIcon";
import FavouriteIcon from "@hugeicons/core-free-icons/FavouriteIcon";
import Sun03Icon from "@hugeicons/core-free-icons/Sun03Icon";
import DiscoverCircleIcon from "@hugeicons/core-free-icons/DiscoverCircleIcon";
const icons = {
  "arrow-up-right": ArrowUpRight01Icon,
  "arrow-left": ArrowLeft01Icon,
  "arrow-right": ArrowRight01Icon,
  rotate: RotateClockwiseIcon,
  heart: FavouriteIcon,
  sun: Sun03Icon,
  compass: DiscoverCircleIcon,
};
const sprite = renderToStaticMarkup(
  createElement(
    "svg",
    { xmlns: "http://www.w3.org/2000/svg" },
    ...Object.entries(icons).map(([id, paths]) =>
      createElement(
        "symbol",
        { id, key: id, viewBox: "0 0 24 24", fill: "none" },
        ...paths.map(([tag, props]) => createElement(tag, props)),
      ),
    ),
  ),
);
await mkdir("public/icons", { recursive: true });
await writeFile(
  "public/icons/ui.svg",
  `<!-- Hugeicons Free · MIT · generated by scripts/export-ui-icons.mjs -->\n${sprite}\n`,
);
