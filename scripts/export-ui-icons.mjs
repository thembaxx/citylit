import { mkdir, writeFile } from "node:fs/promises";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import {
  ArrowUpRight,
  ArrowLeft,
  ArrowRight,
  ArrowClockwise,
  Heart,
  Sun,
  Compass,
} from "@phosphor-icons/react/dist/ssr";
// The offline guide uses the same Phosphor artwork without loading React.
const icons = {
  "arrow-up-right": ArrowUpRight,
  "arrow-left": ArrowLeft,
  "arrow-right": ArrowRight,
  rotate: ArrowClockwise,
  heart: Heart,
  sun: Sun,
  compass: Compass,
};
const symbols = Object.entries(icons)
  .map(([id, Icon]) => {
    const svg = renderToStaticMarkup(createElement(Icon, { weight: "regular" }));
    const paths = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
    return `<symbol id="${id}" viewBox="0 0 256 256" fill="currentColor">${paths}</symbol>`;
  })
  .join("");
await mkdir("public/icons", { recursive: true });
await writeFile(
  "public/icons/ui.svg",
  `<!-- Phosphor Icons · MIT · generated by scripts/export-ui-icons.mjs -->\n<svg xmlns="http://www.w3.org/2000/svg">${symbols}</svg>\n`,
);
